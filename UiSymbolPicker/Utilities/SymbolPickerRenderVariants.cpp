#include "SymbolPickerMaintenance.h"
#include <plugin/z/z.h>

namespace Upp {

bool BuildSymbolPickerRenderVariants(const Vector<SymbolPickerSourceRow>& current, const String& source,
                                    SymbolPickerMaintenanceJob& job, String& header, ValueMap& report)
{
	const char* folders[] = {"materialsymbolsoutlined", "materialsymbolsrounded", "materialsymbolssharp"};
	auto Key = [](const String& name, int style, int optical, bool filled) {
		return name + "/" + AsString(style) + "/" + AsString(optical) + (filled ? "/filled" : "/unfilled");
	};
	Index<String> names;
	VectorMap<String, String> retained;
	for(const auto& row : current) {
		names.FindAdd(row.name);
		if(row.optical_size != 24)
			retained.GetAdd(Key(row.name, row.style, row.optical_size, row.filled)) = row.packed_svg;
	}
	SortIndex(names);
	String table;
	ValueMap hashes;
	ValueArray missing;
	int count = 0, preserved = 0;
	for(const auto& name : names) {
		job.Check(); job.Status("Preparing optical and filled artwork: " + name);
		for(int style = 0; style < 3; ++style) for(int optical : {20, 48}) for(bool filled : {false, true}) {
			String path = "symbols/web/" + name + "/" + folders[style] + "/" + name
				+ (filled ? "_fill1_" : "_") + AsString(optical) + "px.svg";
			String packed, full = AppendFileName(source, path);
			if(FileExists(full)) {
				String svg = LoadFile(full);
				if(svg.IsVoid()) throw Exc("Cannot read " + path);
				try {
					XmlParser parser(svg);
					while(!parser.IsTag() && !parser.IsEof()) parser.Skip();
					if(parser.PeekTag() != "svg") throw Exc("Expected an SVG root.");
					ParseXML(svg);
				}
				catch(const Exc& error) { throw Exc(path + ": " + error); }
				packed = Base64Encode(ZCompress(svg)); hashes.Add(path, SHA256String(svg));
			}
			else {
				int old = retained.Find(Key(name, style, optical, filled));
				if(old >= 0) { packed = retained[old]; ++preserved; }
				else { missing.Add(path); continue; }
			}
			table << " {" << AsCString(name) << ", " << style << ", " << optical << ", "
				<< (filled ? "true" : "false") << ",\n";
			for(int pos = 0; pos < packed.GetCount(); pos += 100)
				table << "  \"" << packed.Mid(pos, 100) << "\"\n";
			table << " },\n"; ++count;
		}
	}
	// A legacy 24-only snapshot can still be compared; do not emit an empty table.
	if(count == 0) return false;
	if(!missing.IsEmpty()) throw Exc(Format("The download is missing %d optical/fill SVGs. Download the complete snapshot before preparing a refresh. First missing: %s", missing.GetCount(), AsString(missing[0])));
	header = "// Generated by native Symbol Picker Utilities. Embedded 20/48 optical SVG designs.\n"
		"#ifndef _SymbolPicker_RenderVariants_h_\n#define _SymbolPicker_RenderVariants_h_\nnamespace Upp {\n"
		"struct SymbolPickerRenderVariant { const char* name; int style, optical; bool filled; const char* packed; };\n"
		"static const SymbolPickerRenderVariant kSymbolPickerRenderVariants[] = {\n" + table
		+ " {nullptr, 0, 0, false, nullptr}\n};\n}\n#endif\n";
	report.Set("variant_count", count); report.Set("preserved_variants", preserved);
	report.Set("optical_sizes", "20,48"); report.Set("source_svg_sha256", hashes);
	return true;
}

}

